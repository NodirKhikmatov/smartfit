export const DICT = { uz, ru };
let current = 'uz';
export const getLang = () => current;

// Own keys only: request data such as a size named "constructor" must never reach Object.prototype.
const own = (lang, key) => (Object.hasOwn(DICT, lang) && Object.hasOwn(DICT[lang], key) ? DICT[lang][key] : undefined);
const fill = (s, vars) => s.replace(/\{(\w+)\}/g, (m, k) => (Object.hasOwn(vars, k) ? String(vars[k]) : m));

// t('kiosk.results.found', { n: 3 }). A missing key shows the key itself, so it is visible in the UI and caught by tests.
export function t(key, vars = {}, lang = current) {
  let v = own(lang, key) ?? own('uz', key) ?? key;
  if (typeof v === 'object') v = v[new Intl.PluralRules(lang).select(vars.n)] ?? v.many;
  return fill(v, vars);
}

// Server error text: vars that are dictionary keys (a field name, "common.size_one") and products ({ name, name_ru })
// are shown in the same language.
export function errorText(lang, key, vars = {}) {
  const local = Object.fromEntries(Object.entries(vars).map(([k, v]) => [k,
    typeof v === 'string' && own('uz', v) !== undefined ? t(v, {}, lang) : v && typeof v === 'object' ? productName(v, lang) : v]));
  return t(key, local, lang);
}

export const productName = (p, lang = current) => (lang === 'ru' && p.name_ru) || p.name;
export const colorName = (c, lang = current) => (lang === 'ru' && c && Object.hasOwn(COLORS_RU, c.toLowerCase()) && COLORS_RU[c.toLowerCase()]) || c;


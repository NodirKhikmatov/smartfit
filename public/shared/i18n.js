// --- Browser only below. The choice is remembered per device; the kiosk resets it to uz on idle.
const saved = () => {
  try { return localStorage.getItem(KEY); } catch { return null; }
};
export function setLang(lang, { remember = true } = {}) {
  current = LANGS.includes(lang) ? lang : 'uz';
  if (remember) try { localStorage.setItem(KEY, current); } catch {}
  document.documentElement.lang = current;
  translate(document);
  return current;
}
export const initLang = () => setLang(saved(), { remember: false });

// Static markup: data-i18n="key" sets the text; data-i18n-aria-label / -title / -placeholder set those attributes.
const ATTRS = ['aria-label', 'title', 'placeholder'];
export function translate(root) {
  for (const e of root.querySelectorAll('[data-i18n]')) e.textContent = t(e.dataset.i18n);
  for (const a of ATTRS) for (const e of root.querySelectorAll(`[data-i18n-${a}]`)) e.setAttribute(a, t(e.getAttribute(`data-i18n-${a}`)));
}

// Two pressed-state chips, each language named in itself (short: "UZ"/"RU", full name as the accessible name).
// onChange runs after the switch.
export function langSwitch(onChange, { short = false } = {}) {
  const box = document.createElement('div');
  box.className = 'lang-switch';
  box.setAttribute('role', 'group');
  box.setAttribute('data-i18n-aria-label', 'common.lang');
  box.setAttribute('aria-label', t('common.lang'));
  const sync = () => box.querySelectorAll('button').forEach((b) => b.setAttribute('aria-pressed', String(b.lang === current)));
  for (const l of LANGS) {
    const name = t(`lang.${l}`, {}, l);
    const b = Object.assign(document.createElement('button'), { type: 'button', className: 'chip', lang: l, textContent: short ? l.toUpperCase() : name });
    if (short) b.setAttribute('aria-label', b.title = name);
    b.onclick = () => {
      if (l === current) return;
      setLang(l);
      sync();
      onChange?.(l);
    };
    box.append(b);
  }
  sync();
  box.sync = sync;
  return box;
}
